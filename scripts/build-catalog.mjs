import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getIconSlug } from "simple-icons/sdk";
import { CATEGORIES, EXTRA_KEYWORDS, FALLBACKS } from "./brand-categories.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "catalog-data.ts");
const HEX = /^[0-9A-F]{6}$/;
const NAME = /^[a-z0-9-]+$/;

const readJson = (...path) =>
    JSON.parse(readFileSync(join(ROOT, "node_modules", ...path), "utf8"));

const served = (iconify) =>
    new Set([
        ...Object.keys(iconify.icons ?? {}),
        ...Object.keys(iconify.aliases ?? {}),
    ]);

function aliasWords(aliases = {}) {
    return [
        ...(aliases.aka ?? []),
        ...(aliases.old ?? []),
        ...(aliases.dup ?? []).map((dup) => dup.title),
        ...Object.values(aliases.loc ?? {}),
    ];
}

const byTitle = (a, b) => {
    const x = a.title.toLowerCase();
    const y = b.title.toLowerCase();
    if (x !== y) return x < y ? -1 : 1;
    return a.name < b.name ? -1 : a.name > b.name ? 1 : 0;
};

// Simple Icons brands are listed only when Iconify serves them; Iconify still
// serves brands that Simple Icons has since removed, and those stay out.
export function buildCatalog(simpleIcons, siIconify, logosIconify, curated) {
    const siServed = served(siIconify);
    const logosServed = served(logosIconify);
    const entries = new Map();
    for (const brand of simpleIcons) {
        const name = getIconSlug(brand);
        if (!siServed.has(name) || !NAME.test(name)) continue;
        if (!HEX.test(brand.hex))
            throw new Error(`${name}: bad hex ${brand.hex}`);
        entries.set(name, {
            name,
            title: brand.title,
            keywords: aliasWords(brand.aliases),
            prefix: "simple-icons",
            hex: brand.hex,
        });
    }
    for (const [name, title] of curated.fallbacks) {
        if (!logosServed.has(name)) throw new Error(`logos has no ${name}`);
        if (entries.has(name)) throw new Error(`${name} is in Simple Icons`);
        entries.set(name, { name, title, keywords: [], prefix: "logos" });
    }
    for (const [name, words] of Object.entries(curated.extraKeywords)) {
        const entry = entries.get(name);
        if (!entry) throw new Error(`extra keywords for unknown ${name}`);
        entry.keywords.push(words);
    }
    for (const group of curated.categories) {
        for (const name of group.names) {
            const entry = entries.get(name);
            if (!entry) throw new Error(`${group.id}: no brand ${name}`);
            entry.keywords.push(group.title.toLowerCase().replace(/&/g, ""));
        }
    }
    const icons = [...entries.values()]
        .map((entry) => ({
            ...entry,
            keywords: entry.keywords.join(" ").replace(/\s+/g, " ").trim(),
        }))
        .sort(byTitle);
    const categories = curated.categories.map(({ id, title, names }) => ({
        id,
        title,
        names: [...names],
    }));
    return { icons, categories };
}

export const CURATED = {
    fallbacks: FALLBACKS,
    extraKeywords: EXTRA_KEYWORDS,
    categories: CATEGORIES,
};

function source(catalog) {
    const version = (...path) => readJson(...path, "package.json").version;
    return (
        `// Generated by scripts/build-catalog.mjs from simple-icons ${version("simple-icons")}, @iconify-json/simple-icons ${version("@iconify-json", "simple-icons")} and @iconify-json/logos ${version("@iconify-json", "logos")}. Do not edit by hand.\n` +
        `import type { CatalogIcon, Category } from "./catalog";\n\n` +
        `export const ICONS: CatalogIcon[] = ${JSON.stringify(catalog.icons)};\n\n` +
        `export const CATEGORIES: Category[] = ${JSON.stringify(catalog.categories)};\n`
    );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const text = source(
        buildCatalog(
            readJson("simple-icons", "data", "simple-icons.json"),
            readJson("@iconify-json", "simple-icons", "icons.json"),
            readJson("@iconify-json", "logos", "icons.json"),
            CURATED
        )
    );
    // Skipping identical writes keeps a second build from dirtying the tree.
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
        writeFileSync(OUT, text);
    }
}
